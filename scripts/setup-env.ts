/**
 * Creates a local `.env` for development with freshly generated secrets.
 * Secrets never go into the repository (CLAUDE.md); `.env` is git-ignored.
 * Existing values are kept, missing ones are added.
 */
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { appPorts, repoRoot, stacks } from "@ep/testing/infra";

const envPath = resolve(repoRoot, ".env");

function parseEnv(text: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const line of text.split("\n")) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match?.[1]) map.set(match[1], match[2] ?? "");
  }
  return map;
}

function sealedBoxKeyPair(): { publicKey: string; secretKey: string } {
  const { publicKey, privateKey } = generateKeyPairSync("x25519");
  const pub = publicKey.export({ format: "jwk" }).x;
  const priv = privateKey.export({ format: "jwk" }).d;
  if (!pub || !priv) throw new Error("x25519 key generation failed");
  return {
    publicKey: Buffer.from(pub, "base64url").toString("base64"),
    secretKey: Buffer.from(priv, "base64url").toString("base64"),
  };
}

const random = (bytes: number) => randomBytes(bytes).toString("base64");
const randomUrlSafe = (bytes: number) => randomBytes(bytes).toString("base64url");

export function ensureDevEnv(): void {
  const existing = existsSync(envPath)
    ? parseEnv(readFileSync(envPath, "utf8"))
    : new Map<string, string>();
  const ports = stacks.dev.ports;
  const pgPassword = existing.get("DEV_POSTGRES_PASSWORD") || randomUrlSafe(18);
  const keyPair =
    existing.get("SEALED_BOX_PUBLIC_KEY") && existing.get("SEALED_BOX_SECRET_KEY")
      ? {
          publicKey: existing.get("SEALED_BOX_PUBLIC_KEY") as string,
          secretKey: existing.get("SEALED_BOX_SECRET_KEY") as string,
        }
      : sealedBoxKeyPair();

  const wanted: Array<[string, string]> = [
    ["APP_ENV", "development"],
    ["LOG_LEVEL", "info"],
    ["DEV_POSTGRES_PASSWORD", pgPassword],
    [
      "DATABASE_URL",
      `postgres://emailplattform:${pgPassword}@127.0.0.1:${ports.pg}/emailplattform`,
    ],
    ["VALKEY_URL", `redis://127.0.0.1:${ports.valkey}`],
    ["VALKEY_PREFIX", "ep"],
    ["MAIL_SEND_MODE", "sandbox"],
    ["MAIL_ALLOWLIST", ""],
    ["SANDBOX_MAIL_HOSTS", "127.0.0.1,localhost,greenmail,mailpit"],
    ["EMAIL_HASH_KEY", random(32)],
    ["WEB_URL", `http://127.0.0.1:${appPorts.dev.web}`],
    ["EDGE_URL", `http://127.0.0.1:${appPorts.dev.edge}`],
    ["WEB_HOST", "127.0.0.1"],
    ["WEB_PORT", String(appPorts.dev.web)],
    ["EDGE_HOST", "127.0.0.1"],
    ["EDGE_PORT", String(appPorts.dev.edge)],
    ["WORKER_HOST", "127.0.0.1"],
    ["WORKER_PORT", String(appPorts.dev.worker)],
    ["BETTER_AUTH_SECRET", randomUrlSafe(48)],
    ["SEALED_BOX_PUBLIC_KEY", keyPair.publicKey],
    ["SEALED_BOX_SECRET_KEY", keyPair.secretKey],
    ["MASTER_KEY", random(32)],
    ["MASTER_KEY_VERSION", "1"],
    ["SYSTEM_MAIL_SMTP_URL", `smtp://127.0.0.1:${ports.mailpitSmtp}`],
    ["SYSTEM_MAIL_FROM", "E-Mail-Plattform <no-reply@plattform.test>"],
    ["PASSWORD_BREACH_CHECK", "off"],
    ["STORAGE_DRIVER", "fs"],
    ["STORAGE_FS_ROOT", resolve(repoRoot, ".data/storage")],
    ["EDGE_BUFFER_DIR", resolve(repoRoot, ".data/edge-buffer")],
    ["RSPAMD_URL", `http://127.0.0.1:${ports.rspamd}`],
    ["CHECK_ADDRESS", "pruefadresse@plattform.test"],
    ["GREENMAIL_API_URL", `http://127.0.0.1:${ports.gmApi}`],
    ["MAILPIT_API_URL", `http://127.0.0.1:${ports.mailpitHttp}`],
  ];

  let changed = false;
  const lines: string[] = [
    "# Local development environment – generated by `pnpm setup:env`. Never commit this file.",
  ];
  for (const [key, value] of wanted) {
    const current = existing.get(key);
    if (current === undefined) changed = true;
    lines.push(`${key}=${current ?? value}`);
  }
  for (const [key, value] of existing) {
    if (!wanted.some(([wantedKey]) => wantedKey === key)) lines.push(`${key}=${value}`);
  }
  if (changed || !existsSync(envPath)) {
    writeFileSync(envPath, `${lines.join("\n")}\n`, { mode: 0o600 });
    console.info(`.env written (${envPath})`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  ensureDevEnv();
}
